import { copyFile, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';

/* Self-host the MapLibre worker from the installed version, rather than
   relying on a CDN or bundler-relative URL. The layout differs per major:
   MapLibre 6 ships an ESM worker plus a sibling shared module; MapLibre 4
   (kept for WebGL2-only machines — old GPUs, blocked hardware acceleration)
   ships only classic workers inside the UMD bundle, so we write a tiny ESM
   shim that hands the bundled worker blob to MapLibre itself. */
const root = new URL('../', import.meta.url);
const source = new URL('node_modules/maplibre-gl/', root);
const { version } = JSON.parse(await readFile(new URL('package.json', source), 'utf8'));
const vendor = new URL('public/vendor/maplibre/', root);
const target = new URL(`${version}/`, vendor);
await mkdir(target, { recursive: true });

const exists = async (url) => readFile(url).then(() => true, () => false);

if (await exists(new URL('dist/maplibre-gl-worker.mjs', source))) {
  // MapLibre 5+/6+: real ESM worker + shared chunk.
  for (const file of ['maplibre-gl-worker.mjs', 'maplibre-gl-shared.mjs', '../LICENSE.txt']) {
    await copyFile(new URL(`dist/${file}`, source), new URL(file.split('/').at(-1), target));
  }
} else if (await exists(new URL('dist/maplibre-gl-csp-worker.js', source))) {
  // MapLibre 4.x: classic worker embedded in maplibre-gl-csp-worker.js.
  const csp = await readFile(new URL('dist/maplibre-gl-csp-worker.js', source), 'utf8');
  const license = await readFile(new URL('dist/LICENSE.txt', source), 'utf8');
  await writeFile(new URL('maplibre-gl-worker.mjs', target), [
    '// Generated by tools/prepare-map-worker.mjs — do not edit.',
    '// Reuses the classic worker embedded in maplibre-gl-csp-worker.js of the',
    '// installed MapLibre build and exposes it as an ESM default export, which',
    '// is what maplibregl.setWorkerUrl() expects.',
    csp.trimEnd(),
    '',
    'export default Worker;',
    '',
  ].join('\n'));
  await writeFile(new URL('LICENSE.txt', target), license);
} else {
  throw new Error(`prepare-map-worker: no known worker layout in maplibre-gl@${version}`);
}

/* These files are committed, because the map hard-fails without them and a
   build that skips npm lifecycle scripts would otherwise ship none. Committing
   them means a stale directory survives a version bump, and a developer keeping
   the old copy is exactly how a broken worker URL passes locally and 404s in
   production. Prune everything but the installed version so the tree can only
   ever hold what the bundle actually asks for. */
for (const entry of await readdir(vendor, { withFileTypes: true })) {
  if (entry.isDirectory() && entry.name !== version) {
    await rm(new URL(`${entry.name}/`, vendor), { recursive: true, force: true });
    console.log(`prepare-map-worker: pruned stale maplibre ${entry.name}`);
  }
}
